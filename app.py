"""CodeMentor's Streamlit interface. A thin view: all behaviour lives in codementor/tutor.py.

Run with:  streamlit run app.py
"""

from __future__ import annotations

import streamlit as st

from codementor.config import load_settings
from codementor.eventlog import EventLog
from codementor.exercises import load_exercises
from codementor.policy import LEVEL_NAMES, summary_for_student
from codementor.runner import (ERROR, FAILED, LOAD_ERROR, NOT_RUN, PASSED, REJECTED, RUN_TIMEOUT,
                               RUNNER_ERROR, SYNTAX_ERROR, TIMEOUT, TestRunner)
from codementor.tutor import (EVIDENCE_CITES_FAILING, EVIDENCE_NO_FAILURES, EVIDENCE_UNCITED, SOURCE_AI, SOURCE_AUTHORED,
                              SOURCE_SYSTEM, HintRecord, TutorSession)

st.set_page_config(page_title="CodeMentor", page_icon="🧭", layout="wide")
st.markdown("<style>textarea { font-family: ui-monospace, SFMono-Regular, Menlo, monospace !important; "
            "font-size: 0.9rem !important; }</style>", unsafe_allow_html=True)

# Every state is shown with an icon AND a word, never colour alone.
TEST_LABELS = {PASSED: "✅ Passed", FAILED: "❌ Failed", ERROR: "💥 Error",
               TIMEOUT: "⏱️ Timed out", NOT_RUN: "➖ Not run"}
RUN_PROBLEMS = {SYNTAX_ERROR: "🧩 Syntax error", REJECTED: "🚫 Not run", LOAD_ERROR: "💥 Error before the tests",
                RUN_TIMEOUT: "⏱️ Time limit", RUNNER_ERROR: "⚠️ Runner problem"}


@st.cache_resource
def get_exercises():
    return load_exercises()


@st.cache_resource
def get_runner():
    return TestRunner()


@st.cache_resource
def get_provider():
    """Returns (provider or None, status line for the sidebar)."""
    settings = load_settings()
    if settings.provider == "scripted":
        from codementor.providers import ScriptedProvider
        try:
            ScriptedProvider.from_file(settings.script_path)
        except Exception as exc:  # missing or malformed script: say so, run offline
            return None, f"📘 **Offline mode.** The demo script could not be loaded ({type(exc).__name__})."
        return None, (f"🎬 **Simulated AI.** Replies are replayed from `{settings.script_path.name}`, "
                      "not generated by a model. Every reply still goes through the hint policy check.")
    return None, "📘 **Offline mode.** No AI model is connected, so hints are pre-written."


def get_session(exercise) -> TutorSession:
    sessions = st.session_state.setdefault("sessions", {})
    if exercise.id not in sessions:
        settings = load_settings()
        provider, _ = get_provider()
        if settings.provider == "scripted":  # a fresh copy of the script for every session
            from codementor.providers import ScriptedProvider
            try:
                provider = ScriptedProvider.from_file(settings.script_path)
            except Exception:
                provider = None
        sessions[exercise.id] = TutorSession(exercise, get_runner(), provider,
                                             EventLog(settings.log_path), settings.max_attempts)
    return sessions[exercise.id]


def level_indicator(level: int) -> str:
    dots = " ".join(("●" if n <= level else "○") + f" {n} {LEVEL_NAMES[n]}" for n in (1, 2, 3))
    current = f"**Level {level} of 3 · {LEVEL_NAMES[level]}**" if level else "**No hints yet**"
    return f"Assistance level: {current}  \n{dots}"


def render_results(session: TutorSession, code: str) -> None:
    run = session.last_run
    st.markdown("#### Test results")
    if run is None:
        st.info("No tests have run yet. Press **Run tests** to see what your code does.")
        return
    if session.is_stale(code):
        st.warning("✏️ You've edited the code since this run. These results are for the earlier version. "
                   "Run the tests again to update them.")
    counts = {status: sum(1 for o in run.outcomes if o.status == status) for status in TEST_LABELS}
    summary = " · ".join(f"{TEST_LABELS[s]} {n}" for s, n in counts.items() if n)
    st.markdown(f"Run {session.run_count}: {summary or 'no tests ran'}")
    if run.status in RUN_PROBLEMS:
        st.error(f"{RUN_PROBLEMS[run.status]}: {run.message}")
    if run.all_passed:
        st.success(f"All {len(run.outcomes)} tests pass. These tests check particular inputs, so passing "
                   "them doesn't prove the function is correct for every input.")
    if run.outcomes:
        rows = []
        for o in run.outcomes:
            if o.status == ERROR:
                got = f"{o.error_type}: {o.error_message}" + (f" (line {o.error_line})" if o.error_line else "")
            elif o.status == TIMEOUT:
                got = "did not finish"
            else:
                got = o.actual_repr or ""
            rows.append({"Result": TEST_LABELS[o.status], "Test": o.test_id, "Call": o.call,
                         "Expected": o.expected_repr, "Got": got, "Checks": o.description})
        st.dataframe(rows, hide_index=True, width="stretch")
    st.caption(f"🔬 **Verified.** These results come from running your code in an isolated process "
               f"({run.isolation}).")
    with st.expander("Tested code, with line numbers", expanded=bool(session.hints)):
        st.code(run.code, language="python", line_numbers=True)


def render_hint(record: HintRecord, latest: bool) -> None:
    with st.container(border=True):
        if record.student_message:
            st.markdown(f"🙋 **You asked:** {record.student_message}")
        if "solution_request" in record.policy_flags:
            st.warning("🙅 CodeMentor is designed to provide hints rather than complete solutions, but its checks may miss some disclosures. "
                       "You can ask for a more specific hint, or change your code and run the tests.")
        if "rule_override" in record.policy_flags:
            st.warning("🔒 Messages cannot override the hint rules. Use the buttons to request more detail; hints restart at Level 1 when the set of failing tests changes.")
        if record.source == SOURCE_SYSTEM:
            st.info(record.text)
            return

        st.markdown(f"💡 **Level {record.level} of 3 · {LEVEL_NAMES[record.level]} hint**"
                    + ("  ·  *latest*" if latest else ""))
        if record.auto_run_reason == "first_run":
            st.caption("🔄 The tests hadn't been run yet, so CodeMentor ran them first.")
        elif record.auto_run_reason == "code_changed":
            st.caption("🔄 Your code had changed since the last run, so the tests were re-run on the current version first.")
        if record.level_reset:
            st.info("🔁 Different tests are failing now, so hints restarted at Level 1 for this new problem.")

        st.markdown(f"**🔬 Evidence (verified by running your code, run {record.run_number})**")
        if record.evidence_items:
            for eid, status, sentence in record.evidence_items:
                st.markdown(f"- {TEST_LABELS.get(status, RUN_PROBLEMS.get(status, status))} · **{eid}** · {sentence}")
        if record.source == SOURCE_AI and record.evidence_status == EVIDENCE_CITES_FAILING:
            st.caption("ℹ️ CodeMentor checked that the tutor cites these failing results. "
                       "It did not check that they back up the explanation below.")
        if record.evidence_status == EVIDENCE_UNCITED:
            st.warning("⚠️ **Does not cite a failing test from this run.** Treat this hint as a suggestion to check, not a finding.")
        elif record.evidence_status == EVIDENCE_NO_FAILURES:
            st.warning("⚠️ **No failing test backs this.** All tests pass, so this is the tutor's opinion only. "
                       "You could check it by calling the function with that input yourself.")

        if record.source == SOURCE_AI and (record.model or "").startswith("scripted"):
            st.markdown("**🎬 Tutor's interpretation** · simulated AI reply (scripted), *not verified*")
        elif record.source == SOURCE_AI:
            st.markdown("**🤖 Tutor's interpretation** · AI-generated, *not verified*")
        elif record.source == SOURCE_AUTHORED:
            st.markdown("**📘 Hint** · pre-written for this exercise")
        else:
            st.markdown("**📋 Guidance** · pre-written, filled in from your test results")
        st.markdown(f"> {record.text}")
        if record.model_flagged_unverified:
            st.caption("❔ The tutor marked part of this explanation as a guess that the tests don't confirm.")

        st.caption(f"🛡️ {record.source_note}")
        if record.attempts:
            with st.expander(f"Hint policy check: {len(record.attempts)} attempt(s)"):
                for a in record.attempts:
                    if a.accepted:
                        st.markdown(f"- Attempt {a.number}: ✅ accepted")
                    elif a.kind == "policy":  # plain categories: the detailed reasons can quote the solution
                        st.markdown(f"- Attempt {a.number}: ⛔ rejected · " + "; ".join(summary_for_student(a.rules)))
                    elif a.kind == "format":
                        st.markdown(f"- Attempt {a.number}: ⛔ rejected · the reply was not in the required format")
                    else:
                        st.markdown(f"- Attempt {a.number}: ⚠️ the AI service did not answer")


def main() -> None:
    exercises = get_exercises()
    provider, provider_status = get_provider()
    runner = get_runner()

    with st.sidebar:
        st.markdown("## 🧭 CodeMentor")
        st.caption("A Python debugging tutor designed to guide you with hints.")
        by_id = {e.id: e for e in exercises}
        exercise = by_id[st.selectbox("Exercise", list(by_id), format_func=lambda i: f"{by_id[i].order}. {by_id[i].title}")]
        st.divider()
        st.markdown(provider_status)
        isolation_icon = "🔒" if runner.use_os_sandbox else "⚠️"
        st.markdown(f"{isolation_icon} **Test runner:** {runner.isolation}")
        st.divider()
        st.markdown("**What CodeMentor can and can't do**")
        st.markdown(
            "- Runs fixed tests on your code and shows the **verified** results.\n"
            "- Gives hints at three levels: **1 Concept → 2 Location → 3 Likely fault**. "
            "You decide when to move up.\n"
            "- Is designed not to give the full solution. Its checks catch common give-aways, but can miss a reworded one.\n"
            "- The tutor's explanations are **AI interpretations**. They can be wrong, so check them against the test results.\n"
            "- Passing the tests doesn't prove your code is correct for every input."
        )

    session = get_session(exercise)
    code_key, question_key, pending_key = (f"{k}_{exercise.id}" for k in ("code", "question", "pending"))
    st.session_state.setdefault(code_key, exercise.starter_code)

    def queue(action: str, escalate: bool = False) -> None:
        """Button callback: remember the action with the code and question exactly as submitted."""
        st.session_state[pending_key] = (action, st.session_state[code_key], escalate,
                                         st.session_state.get(question_key, ""))
        st.session_state[question_key] = ""

    def reset_code() -> None:
        st.session_state[code_key] = exercise.starter_code

    # One form holds the editor, the question box and every button, so each press submits
    # the code currently in the editor. Separate widgets could lose an edit made just before a click.
    with st.form(f"work_{exercise.id}", border=False, enter_to_submit=False):
        left, right = st.columns([1.15, 1], gap="large")
        with right:
            st.markdown("#### Help")
            status = st.empty()

        # Do the pending action before drawing the rest, so the level and buttons are current.
        pending = st.session_state.pop(pending_key, None)
        if pending:
            action, submitted_code, escalate, message = pending
            with status, st.spinner("Running the tests in an isolated process…" if action == "run" else
                                    "Writing a hint and checking it against the hint policy…" if provider else
                                    "Finding a hint…"):
                if action == "run":
                    session.run_tests(submitted_code)
                else:
                    session.request_hint(submitted_code, escalate=escalate, message=message)

        with left:
            st.markdown(f"### {exercise.order}. {exercise.title}")
            st.markdown(exercise.description)
            st.markdown(f"**Expected:** {exercise.expected_behaviour}")
            st.text_area("Your code", key=code_key, height=240)
            b1, b2 = st.columns(2)
            b1.form_submit_button("▶️ Run tests", type="primary", width="stretch", on_click=queue, args=("run",))
            b2.form_submit_button("↩️ Reset to starter code", width="stretch", on_click=reset_code)
            render_results(session, st.session_state[code_key])

        with right:
            level = session.controller.level
            st.markdown(level_indicator(level))
            if session.level_was_reset and level == 0:
                if session.last_run is not None and session.last_run.all_passed:
                    st.info("🔁 All tests pass now, so any new hint starts again from Level 1.")
                else:
                    st.info("🔁 Different tests are failing now, so hints start again from Level 1.")
            if session.hints:
                render_hint(session.hints[-1], latest=True)
            st.text_input("Your question (optional)", key=question_key,
                          placeholder="e.g. Why does my loop stop early?")
            if level == 0:
                st.form_submit_button("💡 Get a hint · Level 1 (Concept)", type="primary", width="stretch",
                                      on_click=queue, args=("hint",))
            else:
                nxt = min(level + 1, 3)
                c1, c2 = st.columns(2)
                c1.form_submit_button(f"💬 Same level ({level})", width="stretch", on_click=queue, args=("hint",),
                                      help="Ask again, or ask a question, without more detail.")
                c2.form_submit_button(f"🔎 More specific ({nxt})", type="primary", width="stretch",
                                      on_click=queue, args=("hint", True), help=f"Level {nxt}: {LEVEL_NAMES[nxt]}",
                                      disabled=not session.controller.can_escalate)
            if level == 3:
                st.caption("Level 3 is the most specific help CodeMentor gives. It is designed to stop short of the solution. "
                           "Try a change and run the tests.")
            earlier = session.hints[:-1]
            if earlier:
                with st.expander(f"Earlier hints ({len(earlier)})"):
                    for record in reversed(earlier):
                        render_hint(record, latest=False)


main()
