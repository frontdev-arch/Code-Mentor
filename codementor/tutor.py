"""One student's session on one exercise: the interaction loop, independent of the UI.

request_hint() is the core pipeline:

  current code -> (re-run tests if the code changed) -> level from HintController
  -> context assembly -> provider -> schema validation -> policy check
  -> accept, or retry naming the broken rules (bounded; never the quoted text) -> fallback hint

The Streamlit app only calls run_tests() and request_hint() and draws the records
they return, so every behaviour here can be tested without a browser.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from codementor.eventlog import EventLog
from codementor.exercises import Exercise
from codementor.hint_controller import HintController
from codementor.policy import LEVEL_NAMES, PolicyContext, check_hint, detect_policy_requests, feedback_for_model
from codementor.prompts import PROMPT_VERSION, HintTurn, build_hint_context, retry_feedback
from codementor.providers import HintProvider, ProviderError
from codementor.runner import ERROR, NOT_RUN, REJECTED, RunResult, TestRunner, code_hash
from codementor.schema import HINT_SCHEMA, HintResponse, validate_hint_response

# Where the hint text came from. The interface labels each one differently.
SOURCE_AI = "ai"                # generated by the model and accepted by the policy checker
SOURCE_AUTHORED = "authored"    # pre-written by the exercise author for the known bug
SOURCE_GENERIC = "generic"      # pre-written template filled with verified test results
SOURCE_SYSTEM = "system"        # a message about the run, not a hint

# How the hint relates to the verified test results.
# Citing a failing test is checked; whether that test backs up the explanation is NOT.
EVIDENCE_CITES_FAILING = "cites_failing_test"   # cites at least one failing result from this run
EVIDENCE_UNCITED = "cites_no_failing_test"      # tests fail, but the hint cites none of them
EVIDENCE_NO_FAILURES = "no_failing_tests" # all tests pass, so no failure backs the hint


@dataclass
class Attempt:
    number: int
    accepted: bool
    raw: str | None = None
    model: str | None = None
    problems: list[str] = field(default_factory=list)  # full detail, developer log only
    kind: str = ""  # "provider", "format" or "policy" when rejected
    rules: list[str] = field(default_factory=list)  # policy rules broken, safe to show or send


@dataclass
class HintRecord:
    source: str
    text: str
    level: int | None = None
    source_note: str = ""
    target_concept: str = ""
    evidence_ids: list[str] = field(default_factory=list)
    evidence_items: list[tuple[str, str, str]] = field(default_factory=list)  # (id, status, sentence) at the time of the hint
    evidence_status: str = ""
    model_flagged_unverified: bool = False
    policy_flags: list[str] = field(default_factory=list)
    attempts: list[Attempt] = field(default_factory=list)
    auto_run_reason: str = ""  # "first_run" or "code_changed" when tests ran automatically first
    level_reset: bool = False  # that automatic run found different failing tests, so the level restarted
    run_hash: str = ""
    run_number: int = 0
    student_message: str = ""
    model: str | None = None

    @property
    def auto_ran_tests(self) -> bool:
        return bool(self.auto_run_reason)

    @property
    def is_hint(self) -> bool:
        return self.level is not None

    @property
    def rejected_attempts(self) -> int:
        return sum(1 for a in self.attempts if not a.accepted)


class TutorSession:
    def __init__(self, exercise: Exercise, runner: TestRunner, provider: HintProvider | None,
                 log: EventLog | None = None, max_attempts: int = 3):
        self.exercise = exercise
        self.runner = runner
        self.provider = provider
        self.log = log or EventLog(None)
        self.max_attempts = max_attempts
        self.controller = HintController()
        self.last_run: RunResult | None = None
        self.run_count = 0
        self.hints: list[HintRecord] = []
        self.level_was_reset = False

    # ----- running tests -------------------------------------------------

    def run_tests(self, code: str) -> RunResult:
        run = self.runner.run(self.exercise, code)
        self.run_count += 1
        self.last_run = run
        tests_ran = any(o.status != NOT_RUN for o in run.outcomes)
        # Only a run where tests executed can change the problem focus; a typo
        # that stops the code loading should not throw away the student's level.
        self.level_was_reset = self.controller.update_focus(run.failing_ids) if tests_ran else False
        self.log.write({"event": "run", "exercise": self.exercise.id, "run": self.run_count,
                        "code_hash": run.code_hash, "status": run.status,
                        "failing": sorted(run.failing_ids), "isolation": run.isolation,
                        "duration_s": run.duration_s, "level_reset": self.level_was_reset})
        return run

    def is_stale(self, code: str) -> bool:
        return self.last_run is not None and self.last_run.code_hash != code_hash(code)

    # ----- hints ---------------------------------------------------------

    def request_hint(self, code: str, escalate: bool = False, message: str = "") -> HintRecord:
        auto_reason = "first_run" if self.last_run is None else "code_changed" if self.is_stale(code) else ""
        level_reset = False
        if auto_reason:
            self.run_tests(code)  # hints are always grounded in results for the code on screen
            level_reset = self.level_was_reset
        run = self.last_run
        flags = detect_policy_requests(message)

        if run.status == REJECTED:
            record = HintRecord(source=SOURCE_SYSTEM, text=f"Your code wasn't run, so there is nothing to diagnose yet. {run.message}")
        elif run.all_passed and not message.strip():
            record = HintRecord(source=SOURCE_SYSTEM, text=(
                f"All {len(run.outcomes)} tests pass. These tests check particular inputs, so passing "
                "them doesn't prove the function is correct for every input."))
        elif run.all_passed and self.provider is None:
            record = HintRecord(source=SOURCE_SYSTEM, text=(
                "All tests pass, and no AI tutor is connected to answer questions about passing code."))
        else:
            level = self.controller.level_for_request(escalate)
            ctx = PolicyContext(self.exercise, level, code, run)
            record = self._generate(ctx, message, flags)
            self.controller.record_hint(level)

        evidence = run.evidence()
        record.evidence_items = [(eid, *evidence[eid]) for eid in record.evidence_ids if eid in evidence]
        record.run_number = self.run_count
        record.policy_flags = flags
        record.auto_run_reason = auto_reason
        record.level_reset = level_reset
        record.run_hash = run.code_hash
        record.student_message = message.strip()
        self.hints.append(record)
        return record

    def _generate(self, ctx: PolicyContext, message: str, flags: list[str]) -> HintRecord:
        level, run = ctx.level, ctx.run
        history = [HintTurn(h.level, h.text, h.student_message) for h in self.hints if h.is_hint]
        assembled = build_hint_context(self.exercise, ctx.student_code, run, level, history, message, flags)
        attempts: list[Attempt] = []
        failure = "No AI model is connected (offline mode)."

        if self.provider is not None:
            feedback = None
            for number in range(1, self.max_attempts + 1):
                try:
                    reply = self.provider.generate(assembled.system, assembled.messages(feedback), HINT_SCHEMA)
                except ProviderError as exc:
                    attempts.append(Attempt(number, accepted=False, problems=[f"provider: {exc}"], kind="provider"))
                    failure = f"The AI tutor is unavailable: {exc}"
                    if not exc.retryable:
                        break
                    continue
                validation = validate_hint_response(reply.text)
                if not validation.ok:
                    attempts.append(Attempt(number, False, reply.text, reply.model, validation.errors, kind="format"))
                    feedback = retry_feedback(validation.errors, level)
                    failure = "The AI reply was not in the required format."
                    continue
                decision = check_hint(validation.response, ctx)
                attempts.append(Attempt(number, decision.accepted, reply.text, reply.model, decision.reasons(),
                                    kind="" if decision.accepted else "policy", rules=decision.rules))
                if decision.accepted:
                    record = self._ai_record(validation.response, run, reply.model, attempts)
                    self._log_hint(ctx, assembled, record, flags)
                    return record
                # Rule names only: the detailed reasons can quote the reference solution.
                feedback = retry_feedback(feedback_for_model(decision.rules), level)
                failure = "The AI hint did not pass the hint policy check."

        record = self._fallback(ctx, failure, attempts)
        self._log_hint(ctx, assembled, record, flags)
        return record

    def _ai_record(self, response: HintResponse, run: RunResult, model: str, attempts: list[Attempt]) -> HintRecord:
        failing = set(run.failing_ids) | ({run.run_level_id} if run.run_level_id else set())
        cited = set(response.evidence_ids)
        if run.all_passed:
            status = EVIDENCE_NO_FAILURES
        elif cited & failing:
            status = EVIDENCE_CITES_FAILING
        else:
            status = EVIDENCE_UNCITED
        rejected = sum(1 for a in attempts if not a.accepted)
        note = "Passed the hint policy check" + (f" after {rejected} rejected attempt(s)." if rejected else ".")
        return HintRecord(source=SOURCE_AI, text=response.hint, level=response.level, source_note=note,
                          target_concept=response.target_concept, evidence_ids=sorted(cited),
                          evidence_status=status,
                          model_flagged_unverified=response.has_unverified_interpretation,
                          attempts=attempts, model=model)

    def _fallback(self, ctx: PolicyContext, failure: str, attempts: list[Attempt]) -> HintRecord:
        level, run, code = ctx.level, ctx.run, ctx.student_code
        failing = sorted(run.failing_ids, key=self._test_order)
        if ctx.known_bug:
            text = self.exercise.authored_hint(level, code)
            check = check_hint(HintResponse(text, "", level, failing, False), ctx)
            if check.accepted:
                return HintRecord(source=SOURCE_AUTHORED, text=text, level=level,
                                  source_note=f"{failure} Showing a pre-written hint for this exercise instead.",
                                  evidence_ids=failing, evidence_status=EVIDENCE_CITES_FAILING, attempts=attempts)
        evidence_id, text = self._generic_hint(level, run)
        return HintRecord(source=SOURCE_GENERIC, text=text, level=level,
                          source_note=f"{failure} Showing pre-written guidance built from your test results instead.",
                          evidence_ids=[evidence_id] if evidence_id else [],
                          evidence_status=EVIDENCE_CITES_FAILING if evidence_id else EVIDENCE_NO_FAILURES,
                          attempts=attempts)

    def _test_order(self, test_id: str) -> int:
        ids = [t.id for t in self.exercise.tests]
        return ids.index(test_id) if test_id in ids else len(ids)

    def _generic_hint(self, level: int, run: RunResult) -> tuple[str | None, str]:
        """Template guidance that restates verified facts plus a debugging strategy. It cannot leak a fix."""
        if run.run_level_id in ("SYNTAX", "LOAD"):
            line = f"line {run.error_line}" if run.error_line else "the line named in the message"
            texts = {
                1: "No test could run, because of a problem before your function was called. Read the error message carefully: it names the problem and roughly where it is.",
                2: f"No test could run. Look at {line} and the line just before it. {run.message}",
                3: f"{run.message} Check {line} for a missing colon, bracket or quote, a misspelt name, or indentation that doesn't line up.",
            }
            return run.run_level_id, texts[level]
        failing = sorted(run.failing_ids, key=self._test_order)
        if not failing:
            return None, "All tests pass. Think about inputs the tests don't cover, such as empty or very large values."
        outcome = run.outcome(failing[0])
        if outcome.status == ERROR and outcome.error_line:
            texts = {
                1: f"Test {outcome.test_id} stopped with {outcome.error_type}. Think about what that kind of error means and which values could cause it for the input {outcome.call}.",
                2: f"Test {outcome.test_id}: {outcome.summary()} Look at line {outcome.error_line} and work out the value of each name on that line for this input.",
                3: f"Test {outcome.test_id}: {outcome.summary()} The operation on line {outcome.error_line} can't handle one of its values for this input. Check what that value is and whether the description says this case needs special handling.",
            }
        else:
            texts = {
                1: f"Test {outcome.test_id}: {outcome.summary()} What is different about this input compared with the tests that pass?",
                2: f"Test {outcome.test_id}: {outcome.summary()} Trace your code by hand with this input, writing down each variable's value after every line.",
                3: f"Test {outcome.test_id}: {outcome.summary()} Trace the code with this input; the first line where a value differs from what the description implies is the most likely fault. Check its condition, starting value or return value.",
            }
        return outcome.test_id, texts[level]

    def _log_hint(self, ctx: PolicyContext, assembled, record: HintRecord, flags: list[str]) -> None:
        self.log.write({
            "event": "hint", "exercise": self.exercise.id, "level": ctx.level,
            "previous_level": self.controller.level, "known_bug": ctx.known_bug,
            "policy_flags": flags,
            "run_hash": ctx.run.code_hash, "failing": sorted(ctx.run.failing_ids),
            "prompt_version": PROMPT_VERSION, "prompt": assembled.user,
            "provider": getattr(self.provider, "name", "offline"),
            "model": getattr(self.provider, "model", None),
            "attempts": [a.__dict__ for a in record.attempts],
            "source": record.source, "text": record.text,
            "evidence_ids": record.evidence_ids, "evidence_status": record.evidence_status,
            "model_flagged_unverified": record.model_flagged_unverified,
        })

    @property
    def level_name(self) -> str:
        return LEVEL_NAMES.get(self.controller.level, "None yet")
